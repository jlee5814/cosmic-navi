#!/usr/bin/env python3
"""Lists the ETC items NPC gear recipes consume that are not maker materials (leather, screws, skins, tails),
from the recipe tables in scripts/npc/*.js. Writes src/main/resources/bots/crafting-parts.csv, which the bots
read to keep these items for crafting instead of selling them (BotInventoryManager.isCraftingPart).

usage: python3 tools/bots/gen_crafting_parts.py  (from the repo root; rerun when NPC scripts change)
"""
import glob, json, os, re

def maker_material(i):
    return (4004000 <= i <= 4005004 or 4007000 <= i <= 4007007 or 4010000 <= i <= 4011008
            or 4020000 <= i <= 4021009 or i // 10000 in (413, 426))

parts = {}  # item id -> [largest amount one recipe needs, recipes using it]
for f in sorted(glob.glob('scripts/npc/*.js')):
    s = open(f, encoding='utf-8', errors='ignore').read()
    cur = {}
    def flush():
        if 'itemSet' not in cur or 'matSet' not in cur:
            return
        qtys = cur.get('matQtySet') or [1] * len(cur['itemSet'])
        for i, out in enumerate(cur['itemSet']):
            if out >= 2000000 or i >= len(cur['matSet']) or i >= len(qtys):
                continue  # gear recipes only
            mats, q = cur['matSet'][i], qtys[i]
            if not isinstance(mats, list):
                mats, q = [mats], [q]
            for m, n in zip(mats, q):
                if 4000000 <= m < 4031000 and not maker_material(m):  # ETC, below the quest item ranges
                    p = parts.setdefault(m, [0, 0])
                    p[0] = max(p[0], n)
                    p[1] += 1
    for t in re.finditer(r'var\s+(itemSet|matSet|matQtySet|costSet)\s*=\s*(\[[^;]*?\]);', s, re.S):
        try:
            val = json.loads(t.group(2))
        except ValueError:
            continue
        if t.group(1) == 'itemSet' and 'itemSet' in cur:
            flush()
            cur = {}
        cur[t.group(1)] = val
    flush()

os.makedirs('src/main/resources/bots', exist_ok=True)
with open('src/main/resources/bots/crafting-parts.csv', 'w') as out:
    out.write('# Generated by tools/bots/gen_crafting_parts.py from scripts/npc/*.js; do not edit by hand.\n')
    out.write('# itemId,maxPerRecipe,recipes\n')
    for i in sorted(parts):
        out.write(f'{i},{parts[i][0]},{parts[i][1]}\n')
print(len(parts), 'crafting parts')
