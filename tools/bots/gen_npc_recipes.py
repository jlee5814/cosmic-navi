#!/usr/bin/env python3
"""Exports the NPC crafting and refining recipes in scripts/npc/*.js (the itemSet / matSet / matQtySet / costSet
tables) to src/main/resources/bots/npc-recipes.csv, which the bots read to craft on demand (BotCraftManager) and
to keep the parts recipes need (BotInventoryManager.isCraftingPart).

usage: python3 tools/bots/gen_npc_recipes.py  (from the repo root; rerun when NPC scripts change)
"""
import glob, json, os, re

def yield_of(script, out):
    """How many one craft gives: the scripts' recvQty rules (15 screws; arrow bundles), else 1."""
    if out == 4003000 and 'recvQty = 15 * qty' in script:
        return 15
    if 2060000 <= out < 2060100 and '1000 - (item - 2060000) * 100' in script:
        return 1000 - (out - 2060000) * 100
    if 2061000 <= out < 2061100 and '1000 - (item - 2061000) * 100' in script:
        return 1000 - (out - 2061000) * 100
    return 1

rows = []
for f in sorted(glob.glob('scripts/npc/*.js')):
    name = os.path.basename(f)[:-3]
    if not name.isdigit():
        continue  # old or helper scripts
    npc = int(name)
    s = open(f, encoding='utf-8', errors='ignore').read()
    cur = {}
    def flush():
        if 'itemSet' not in cur or 'matSet' not in cur:
            return
        items = cur['itemSet']
        qtys = cur.get('matQtySet') or [1] * len(items)
        costs = cur.get('costSet') or [0] * len(items)
        for i, out in enumerate(items):
            if i >= len(cur['matSet']) or i >= len(qtys):
                continue
            mats, q = cur['matSet'][i], qtys[i]
            if not isinstance(mats, list):
                mats, q = [mats], [q]
            if len(mats) != len(q) or not all(isinstance(x, int) for x in list(mats) + list(q) + [out]):
                continue
            fee = costs[i] if i < len(costs) and isinstance(costs[i], int) else 0
            rows.append((npc, out, fee, ';'.join(f'{m}:{n}' for m, n in zip(mats, q)), yield_of(s, out)))
    for t in re.finditer(r'var\s+(itemSet|matSet|matQtySet|costSet)\s*=\s*(\[[^;]*?\]);', s, re.S):
        try:
            val = json.loads(t.group(2))
        except ValueError:
            continue
        if t.group(1) == 'itemSet' and 'itemSet' in cur:
            flush()
            cur = {}
        cur[t.group(1)] = val
    flush()

os.makedirs('src/main/resources/bots', exist_ok=True)
with open('src/main/resources/bots/npc-recipes.csv', 'w') as out:
    out.write('# Generated by tools/bots/gen_npc_recipes.py from scripts/npc/*.js; do not edit by hand.\n')
    out.write('# npcId,outputId,fee,materialId:qty;...,yield (how many one craft gives)\n')
    for r in rows:
        out.write(f'{r[0]},{r[1]},{r[2]},{r[3]},{r[4]}\n')
print(len(rows), 'recipes')
