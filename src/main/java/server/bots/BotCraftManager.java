/**
 * Crafting on demand, the way a player gets gear an NPC makes: when a recipe would give the bot an upgrade it can
 * wear now, and it holds the materials (refining ores into plates and plates into screws on the way), it walks to
 * the NPC and crafts, then wears the result. The recipes are the NPC scripts' own tables
 * ({@code src/main/resources/bots/npc-recipes.csv}, generated by tools/bots/gen_npc_recipes.py), and a craft does
 * what the script does: {@code gainItem(material, -qty)}, {@code gainMeso(-fee)}, {@code gainItem(output, n)}, with
 * the same random stat roll a scripted craft gives. A plan only runs when crafting costs less than getting the item
 * another way (a shop's price or the farming effort, {@link BotScrollManager#scrollMarketValueMeso}).
 */
final class BotCraftManager {
    private static final Logger log = LoggerFactory.getLogger(BotCraftManager.class);

    private BotCraftManager() {}

    // ---- recipes ----------------------------------------------------------------------------------------------

    record Mat(int itemId, int qty) {}

    /** One NPC recipe: {@code yield} of {@code outputId} for {@code mats} and {@code fee} meso, per craft. */
    record Recipe(int npcId, int outputId, int fee, List<Mat> mats, int yield) {
        boolean gear() {
            return outputId < 2000000;
        }
    }

    static final List<Recipe> RECIPES = load();
    private static final Map<Integer, List<Recipe>> BY_OUTPUT = byOutput(RECIPES);

    private static List<Recipe> load() {
        List<Recipe> out = new ArrayList<>();
        try (var in = BotCraftManager.class.getResourceAsStream("/bots/npc-recipes.csv")) {
            if (in == null) {
                return out;
            }
            for (String line : new String(in.readAllBytes(), java.nio.charset.StandardCharsets.UTF_8).split("\n")) {
                String l = line.trim();
                if (l.isEmpty() || l.startsWith("#")) {
                    continue;
                }
                String[] f = l.split(",");
                List<Mat> mats = new ArrayList<>();
                for (String m : f[3].split(";")) {
                    String[] p = m.split(":");
                    mats.add(new Mat(Integer.parseInt(p[0]), Integer.parseInt(p[1])));
                }
                out.add(new Recipe(Integer.parseInt(f[0]), Integer.parseInt(f[1]), Integer.parseInt(f[2]),
                        List.copyOf(mats), f.length > 4 ? Integer.parseInt(f[4]) : 1));
            }
        } catch (java.io.IOException | RuntimeException e) {
            log.warn("npc recipes unreadable", e);
        }
        return List.copyOf(out);
    }

    private static Map<Integer, List<Recipe>> byOutput(List<Recipe> recipes) {
        Map<Integer, List<Recipe>> m = new HashMap<>();
        for (Recipe r : recipes) {
            m.computeIfAbsent(r.outputId(), k -> new ArrayList<>()).add(r);
        }
        return m;
    }

    /** The ETC items gear recipes consume besides maker materials, with the most one recipe needs of each. */
    static Map<Integer, Integer> craftingPartsMaxPerRecipe() {
        Map<Integer, Integer> parts = new HashMap<>();
        for (Recipe r : RECIPES) {
            if (!r.gear()) {
                continue;
            }
            for (Mat m : r.mats()) {
                int id = m.itemId();
                if (id >= 4000000 && id < 4031000 && !BotInventoryManager.isMakerMaterial(id)) {
                    parts.merge(id, m.qty(), Math::max);
                }
            }
        }
        return parts;
    }

    // ---- planning ---------------------------------------------------------------------------------------------

    /** Craft {@code recipe} this many times, in order; the last step is the goal. */
    record Step(Recipe recipe, int times) {}

    record Plan(Recipe goal, List<Step> steps, long fees, double inputValue, double gain) {}

    private static final int MAX_CHAIN_DEPTH = 3;      // gear <- screws <- plates <- ores
    static final int OUTGROWN_LEVELS = 20;             // gear this far under the bot's level isn't worth a trip

    /** Test seams: item data, prices and the bot's worn offense (all WZ, DB or live state). */
    interface Lookups {
        Map<String, Integer> stats(int itemId);       // equip info: reqLevel, reqJob, PAD, MAD, STR...
        double offense(Character bot, Map<String, Integer> stats);
        double wornOffense(Character bot, int slot);   // what it wears in that slot, 0 when nothing
        boolean wearable(Character bot, int itemId);   // job, level and stats now
        boolean preferredWeapon(Character bot, int itemId);
        int sellPrice(int itemId, int qty);
        double obtainCost(Character bot, int itemId);  // a shop's price, else the farming effort
    }

    static Lookups lookups = new Lookups() {
        private final ItemInformationProvider ii() { return ItemInformationProvider.getInstance(); }
        @Override public Map<String, Integer> stats(int itemId) { return ii().getEquipStats(itemId); }
        @Override public double offense(Character bot, Map<String, Integer> stats) {
            return BotScrollManager.offenseValueFromStats(bot, stats);
        }
        @Override public double wornOffense(Character bot, int slot) {
            double best = 0;
            for (Item it : bot.getInventory(InventoryType.EQUIPPED).list()) {
                if (it instanceof Equip e && !ii().isCash(e.getItemId()) && BotStorageMuleManager.gearSlot(e.getItemId()) == slot) {
                    best = Math.max(best, BotScrollManager.offenseValue(bot, e));
                }
            }
            return best;
        }
        @Override public boolean wearable(Character bot, int itemId) {
            Item it = ii().getEquipById(itemId);
            return it instanceof Equip e && ii().meetsEquipRequirements(e, bot.getJob(), bot.getLevel(),
                    bot.getTotalStr(), bot.getTotalDex(), bot.getTotalInt(), bot.getTotalLuk(), bot.getFame());
        }
        @Override public boolean preferredWeapon(Character bot, int itemId) {
            WeaponType type = ii().getWeaponType(itemId);
            return BotEquipManager.isPreferredWeapon(bot, type);
        }
        @Override public int sellPrice(int itemId, int qty) { return BotInventoryManager.sellPrice.price(itemId, qty); }
        @Override public double obtainCost(Character bot, int itemId) {
            return BotScrollManager.scrollMarketValueMeso(bot, itemId);
        }
    };

    /** What the bot holds in its bag, by item id (equips count one each). */
    static Map<Integer, Integer> bagCounts(Character bot) {
        Map<Integer, Integer> have = new HashMap<>();
        for (InventoryType t : List.of(InventoryType.EQUIP, InventoryType.USE, InventoryType.ETC)) {
            Inventory inv = bot.getInventory(t);
            for (Item it : inv == null ? List.<Item>of() : inv.list()) {
                have.merge(it.getItemId(), Math.max(1, (int) it.getQuantity()), Integer::sum);
            }
        }
        return have;
    }

    /**
     * The best craft for this bot now, or null: gear recipes whose output it can wear, of its preferred weapon
     * type, that beat what it wears in that slot by the job's offense weights, and whose materials its bag covers
     * (refining on the way). Cheaper than getting the item another way, and affordable with half its meso.
     */
    static Plan bestPlan(Character bot, Map<Integer, Integer> have, long meso) {
        Plan best = null;
        for (Recipe r : RECIPES) {
            if (!r.gear()) {
                continue;
            }
            Map<String, Integer> st = lookups.stats(r.outputId());
            if (st == null || st.getOrDefault("cash", 0) > 0) {
                continue;
            }
            int req = st.getOrDefault("reqLevel", 0);
            if (req > bot.getLevel() || req < bot.getLevel() - OUTGROWN_LEVELS) {
                continue;
            }
            int slot = BotStorageMuleManager.gearSlot(r.outputId());
            double gain = lookups.offense(bot, st) - lookups.wornOffense(bot, slot);
            if (gain <= 0 || (best != null && gain < best.gain())) {
                continue;
            }
            Plan p = plan(bot, r, have, gain);
            if (p == null || p.fees() * 2 > meso
                    || p.fees() + p.inputValue() >= lookups.obtainCost(bot, r.outputId())) {
                continue;
            }
            if (ItemConstants.isWeapon(r.outputId()) && !lookups.preferredWeapon(bot, r.outputId())) {
                continue;
            }
            if (!lookups.wearable(bot, r.outputId())) {
                continue;
            }
            if (best == null || gain > best.gain() || (gain == best.gain()
                    && p.fees() + p.inputValue() < best.fees() + best.inputValue())) {
                best = p;
            }
        }
        return best;
    }

    /** The steps that make one {@code goal} from {@code have}, refining what's short, or null when it can't. */
    static Plan plan(Character bot, Recipe goal, Map<Integer, Integer> have, double gain) {
        Map<Integer, Integer> left = new HashMap<>(have);
        List<Step> steps = new ArrayList<>();
        double[] value = new double[1];
        for (Mat m : goal.mats()) {
            if (!resolve(m.itemId(), m.qty(), goal.npcId(), left, steps, value, 0)) {
                return null;
            }
        }
        steps.add(new Step(goal, 1));
        long fees = 0;
        for (Step s : steps) {
            fees += (long) s.recipe().fee() * s.times();
        }
        return new Plan(goal, List.copyOf(steps), fees, value[0], gain);
    }

    // Takes qty of itemId from what's left, crafting the shortfall (ETC recipes only, preferring the NPC the
    // parent recipe uses, so one stop does both). Steps come out in the order they must run.
    private static boolean resolve(int itemId, int qty, int preferNpc, Map<Integer, Integer> left,
                                   List<Step> steps, double[] value, int depth) {
        int held = left.getOrDefault(itemId, 0);
        int use = Math.min(held, qty);
        if (use > 0) {
            left.put(itemId, held - use);
            value[0] += lookups.sellPrice(itemId, use);
        }
        int shortfall = qty - use;
        if (shortfall == 0) {
            return true;
        }
        if (depth >= MAX_CHAIN_DEPTH || itemId < 4000000) {
            return false; // base gear can't be crafted here, and chains stop at ores
        }
        List<Recipe> makers = new ArrayList<>(BY_OUTPUT.getOrDefault(itemId, List.of()));
        makers.sort((a, b) -> Boolean.compare(b.npcId() == preferNpc, a.npcId() == preferNpc));
        for (Recipe r : makers) {
            if (r.gear()) {
                continue;
            }
            int times = (shortfall + r.yield() - 1) / r.yield();
            Map<Integer, Integer> tryLeft = new HashMap<>(left);
            List<Step> trySteps = new ArrayList<>(steps);
            double[] tryValue = {value[0]};
            boolean ok = true;
            for (Mat m : r.mats()) {
                if (!resolve(m.itemId(), m.qty() * times, r.npcId(), tryLeft, trySteps, tryValue, depth + 1)) {
                    ok = false;
                    break;
                }
            }
            if (ok) {
                trySteps.add(new Step(r, times));
                tryLeft.merge(itemId, times * r.yield() - shortfall, Integer::sum);
                left.clear();
                left.putAll(tryLeft);
                steps.clear();
                steps.addAll(trySteps);
                value[0] = tryValue[0];
                return true;
            }
        }
        return false;
    }

    // ---- the errand -------------------------------------------------------------------------------------------

    private static final long CHECK_EVERY_MS = 10 * 60_000L;
    private static final long STALL_MS = 4 * 60_000L;

    static boolean active(BotEntry entry) {
        return entry != null && entry.craftErrandMapId != -1;
    }

    /** Another errand owns the bot, or it's with its owner: no craft trip now. */
    private static boolean busy(BotEntry entry) {
        return entry.following || entry.shopVisitPending || entry.autopilotErrandMapId != -1
                || entry.jobErrandMapId != -1 || entry.questErrandMapId != -1 || entry.gachaErrandMapId != -1
                || BotStorageMuleManager.visitActive(entry);
    }

    /** Look for a craft now and then; start the errand when there is one. */
    static void maybeStart(BotEntry entry, Character bot) {
        long now = System.currentTimeMillis();
        if (active(entry) || now < entry.craftNextCheckAtMs) {
            return;
        }
        entry.craftNextCheckAtMs = now + CHECK_EVERY_MS + ThreadLocalRandom.current().nextLong(CHECK_EVERY_MS);
        if (busy(entry) || bot.getMap() == null) {
            return;
        }
        Plan plan = bestPlan(bot, bagCounts(bot), bot.getMeso());
        if (plan == null) {
            return;
        }
        entry.craftSteps.clear();
        entry.craftSteps.addAll(plan.steps());
        entry.craftGoalId = plan.goal().outputId();
        entry.craftProgress.begin(now);
        if (!nextStop(entry, bot)) {
            clear(entry);
            return;
        }
        String name = ItemInformationProvider.getInstance().getName(entry.craftGoalId);
        log.info("craft: {} plans {} ({} steps, {} meso)", bot.getName(), name, plan.steps().size(), plan.fees());
        BotManager.getInstance().botReply(entry, BotManager.randomReply(List.of(
                "gonna get a " + name + " made, brb", "i have the mats for a " + name + ", going to craft it",
                "heading to the npc to make a " + name)));
    }

    /** Points the errand at the nearest map with the next step's NPC; false when none is reachable. */
    private static boolean nextStop(BotEntry entry, Character bot) {
        Step step = entry.craftSteps.peekFirst();
        if (step == null) {
            return false;
        }
        int npc = step.recipe().npcId();
        int from = bot.getMapId();
        int best = -1;
        int bestHops = Integer.MAX_VALUE;
        for (int mapId : BotSpawnIndex.mapsWithNpc(npc)) {
            if (mapId == from) {
                best = mapId;
                break;
            }
            List<Integer> route = BotAutopilotManager.routeForBot(bot, from, mapId,
                    BotAutopilotManager.MAX_TRAVEL_HOPS, BotAutopilotManager.travelOptions(bot, false));
            if (route != null && route.size() < bestHops) {
                best = mapId;
                bestHops = route.size();
            }
        }
        if (best == -1) {
            return false;
        }
        entry.craftNpcId = npc;
        entry.craftErrandMapId = best;
        return true;
    }

    static boolean tick(BotEntry entry, Character bot, boolean runAiTick) {
        if (!active(entry)) {
            return false;
        }
        long now = System.currentTimeMillis();
        if (entry.craftProgress.stalled(now, STALL_MS)) {
            finish(entry, bot, "couldn't get to the crafting npc, maybe later");
            return false;
        }
        BotTravelManager.ApproachStatus status = BotTravelManager.tickApproachNpc(entry, bot,
                entry.craftErrandMapId, entry.craftNpcId, BotAutopilotManager.MAX_TRAVEL_HOPS, runAiTick, false,
                BotGachaponManager.NPC_TRIGGER_RADIUS_PX);
        entry.craftProgress.record(bot, status == BotTravelManager.ApproachStatus.TRAVELING, now);
        switch (status) {
            case NPC_GONE -> {
                finish(entry, bot, "the crafting npc isn't here, never mind");
                return false;
            }
            case TRAVEL_YIELDED -> {
                BotManager.npcDwellReset(entry);
                return false;
            }
            case TRAVELING -> {
                return true;
            }
            case WALKING -> {
                BotManager.npcDwellReset(entry);
                return true;
            }
            default -> { } // ARRIVED
        }
        entry.craftProgress.touch(now);
        if (!BotManager.npcDwellReady(entry, BotManager.NPC_TALK_DELAY_MS, BotManager.NPC_TALK_JITTER_MS)) {
            return true; // talking to the npc
        }
        BotManager.npcDwellReset(entry); // the next step talks again
        String goal = ItemInformationProvider.getInstance().getName(entry.craftGoalId);
        Step step = entry.craftSteps.pollFirst();
        if (step == null || !craft(bot, step)) {
            finish(entry, bot, "hmm, i'm short on something for the " + goal + ", never mind");
            return false;
        }
        if (entry.craftSteps.isEmpty()) {
            BotEquipManager.autoEquip(bot, entry.owner, null);
            finish(entry, bot, BotManager.randomReply(List.of("got my new " + goal + "!", "crafted it, nice",
                    "done crafting, back to it")));
            return false;
        }
        if (entry.craftSteps.peekFirst().recipe().npcId() != entry.craftNpcId && !nextStop(entry, bot)) {
            finish(entry, bot, "can't find the next npc, never mind");
            return false;
        }
        return true;
    }

    /**
     * One step at the NPC, as its script does it: checks the materials, the fee and room, then
     * {@code gainItem(mat, -qty)}, {@code gainMeso(-fee)}, {@code gainItem(output, yield)}. False when short.
     */
    static boolean craft(Character bot, Step step) {
        Recipe r = step.recipe();
        int n = step.times();
        var cm = bot.getClient().getAbstractPlayerInteraction();
        for (Mat m : r.mats()) {
            if (!cm.haveItem(m.itemId(), m.qty() * n)) {
                return false;
            }
        }
        if (bot.getMeso() < (long) r.fee() * n || !cm.canHold(r.outputId(), r.yield() * n)) {
            return false;
        }
        for (Mat m : r.mats()) {
            cm.gainItem(m.itemId(), (short) -(m.qty() * n));
        }
        bot.gainMeso(-r.fee() * n);
        if (r.gear()) {
            for (int i = 0; i < n; i++) {
                cm.gainItem(r.outputId(), (short) 1); // random stats, like the script's gainItem
            }
        } else {
            cm.gainItem(r.outputId(), (short) (r.yield() * n));
        }
        return true;
    }

    private static void finish(BotEntry entry, Character bot, String say) {
        clear(entry);
        if (say != null) {
            BotManager.getInstance().botReply(entry, say);
        }
    }

    static void clear(BotEntry entry) {
        if (entry.craftErrandMapId != -1) {
            BotTravelManager.clearMoveTargetPin(entry);
            BotTravelManager.clearNpcApproach(entry);
            BotManager.npcDwellReset(entry);
        }
        entry.craftErrandMapId = -1;
        entry.craftNpcId = 0;
        entry.craftSteps.clear();
        entry.craftGoalId = 0;
        entry.craftProgress.clear();
    }
}
